#!/usr/bin/env node
import { readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";

async function bundleRuntime(runtimeDir) {
  const directory = resolve(runtimeDir);
  const source = await readFile(join(directory, "jags.js"), "utf8");
  const wasmBase64 = (await readFile(join(directory, "jags.wasm"))).toString("base64");
  const output = `// Generated by wasm-port/tools/bundle-file-runtime.mjs.
// This bundle embeds jags.wasm so demos can be opened from file:// URLs.
(() => {
  const wasmBase64 = "${wasmBase64}";
  let wasmBinaryCache = null;

  function decodeWasmBinary() {
    if (wasmBinaryCache) {
      return wasmBinaryCache;
    }
    const binary = atob(wasmBase64);
    const bytes = new Uint8Array(binary.length);
    const chunkSize = 32768;
    for (let offset = 0; offset < binary.length; offset += chunkSize) {
      const chunk = binary.slice(offset, offset + chunkSize);
      for (let index = 0; index < chunk.length; index += 1) {
        bytes[offset + index] = chunk.charCodeAt(index);
      }
    }
    wasmBinaryCache = bytes;
    return wasmBinaryCache;
  }

${source}

  globalThis.__jagsRuntimeFactory = (moduleArg = {}) => createJagsModule({
    ...moduleArg,
    wasmBinary: moduleArg.wasmBinary || decodeWasmBinary(),
  });
})();
`;
  await writeFile(join(directory, "jags-file.js"), output);
  console.log(`Wrote ${join(directory, "jags-file.js")}`);
}

if (process.argv.length <= 2) {
  console.error("Usage: node wasm-port/tools/bundle-file-runtime.mjs <runtime-dir> [runtime-dir...]");
  process.exit(1);
}

for (const runtimeDir of process.argv.slice(2)) {
  await bundleRuntime(runtimeDir);
}
